const DEFAULT_ICON_VIEW_BOX = '0 0 24 24'
const ICON_DEFINITION_MARKER = Symbol('GitSyncIconDefinition')
const SUPPORTED_ICON_ELEMENT_TYPES = new Set([
  'path',
  'rect',
  'circle',
  'ellipse',
  'line',
  'polyline',
  'polygon',
])
const PRESENTATION_ATTRIBUTE_NAMES = new Set([
  'class',
  'className',
  'style',
  'color',
  'role',
  'tabIndex',
  'title',
])
const ROOT_PRESENTATION_ATTRIBUTE_NAMES = new Set(['width', 'height'])
const CURRENT_COLOR_ATTRIBUTES = new Set(['fill', 'stroke'])
const ALLOWED_COLOR_MODES = new Set(['currentColor', 'none'])

function hasGeometryValue(value) {
  return value !== undefined && value !== null && value !== ''
}

function assertGeometryAttribute(name, value, scope, root) {
  if (
    PRESENTATION_ATTRIBUTE_NAMES.has(name)
    || (root && ROOT_PRESENTATION_ATTRIBUTE_NAMES.has(name))
    || name.startsWith('aria-')
    || name.startsWith('data-')
    || /^on[A-Z]/.test(name)
  ) {
    throw new TypeError(`${scope} cannot own presentation attribute: ${name}`)
  }
  if (!['string', 'number', 'boolean'].includes(typeof value)) {
    throw new TypeError(`${scope}.${name} must be a serializable geometry value`)
  }
  if (CURRENT_COLOR_ATTRIBUTES.has(name) && !ALLOWED_COLOR_MODES.has(value)) {
    throw new TypeError(`${scope}.${name} must use currentColor or none`)
  }
}

function freezeGeometryAttributes(attributes, scope, { root = false } = {}) {
  const source = attributes && typeof attributes === 'object' && !Array.isArray(attributes)
    ? attributes
    : {}
  const normalized = {}
  for (const [name, value] of Object.entries(source)) {
    if (value === undefined || value === null) continue
    assertGeometryAttribute(name, value, scope, root)
    normalized[name] = value
  }
  return Object.freeze(normalized)
}

function assertRequiredElementAttributes(type, attributes, index) {
  const requiredByType = {
    path: ['d'],
    rect: ['width', 'height'],
    circle: ['r'],
    ellipse: ['rx', 'ry'],
    line: ['x1', 'y1', 'x2', 'y2'],
    polyline: ['points'],
    polygon: ['points'],
  }
  for (const name of requiredByType[type] || []) {
    if (!hasGeometryValue(attributes[name])) {
      throw new TypeError(`icon element ${index} (${type}) requires ${name}`)
    }
  }
}

function freezeIconElement(element, index) {
  if (!element || typeof element !== 'object' || Array.isArray(element)) {
    throw new TypeError(`icon element ${index} must be an object`)
  }
  const { type, ...attributes } = element
  if (!SUPPORTED_ICON_ELEMENT_TYPES.has(type)) {
    throw new TypeError(`unsupported icon element type: ${String(type)}`)
  }
  assertRequiredElementAttributes(type, attributes, index)
  return Object.freeze({
    type,
    ...freezeGeometryAttributes(attributes, `icon element ${index}`),
  })
}

export function defineIcon({ viewBox = DEFAULT_ICON_VIEW_BOX, svg = {}, elements } = {}) {
  if (typeof viewBox !== 'string' || !viewBox.trim()) {
    throw new TypeError('icon viewBox must be a non-empty string')
  }
  if (!Array.isArray(elements) || elements.length === 0) {
    throw new TypeError('icon elements must contain at least one geometry element')
  }

  const definition = {
    viewBox: viewBox.trim(),
    svg: freezeGeometryAttributes(svg, 'icon svg', { root: true }),
    elements: Object.freeze(elements.map(freezeIconElement)),
  }
  Object.defineProperty(definition, ICON_DEFINITION_MARKER, { value: true })
  return Object.freeze(definition)
}

export function isIconDefinition(value) {
  return Boolean(value && value[ICON_DEFINITION_MARKER] === true)
}

function stableSerialize(value) {
  if (Array.isArray(value)) {
    return `[${value.map(stableSerialize).join(',')}]`
  }
  if (value && typeof value === 'object') {
    const entries = Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableSerialize(value[key])}`)
    return `{${entries.join(',')}}`
  }
  return JSON.stringify(value)
}

export function getIconDefinitionSignature(icon) {
  if (!isIconDefinition(icon)) {
    throw new TypeError('expected a valid IconDefinition')
  }
  return stableSerialize({
    viewBox: icon.viewBox,
    svg: icon.svg,
    elements: icon.elements,
  })
}

function defineFilledPathIcon(d) {
  return defineIcon({
    svg: { fill: 'currentColor' },
    elements: [{ type: 'path', d }],
  })
}

